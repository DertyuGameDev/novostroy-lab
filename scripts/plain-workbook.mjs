// Plain, single-sheet data export. Uses the shared authoring runtime only.
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {tableHeaders,tableRows,toCsv} from './table-data.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const {records}=JSON.parse(await readFile(path.join(root,'data/complexes.json'),'utf8'));
const out=path.join(root,'outputs/2026-11-13-unified');await mkdir(out,{recursive:true});
const wb=Workbook.create(),sheet=wb.worksheets.add('ЖК');
const rows=tableRows(records);
const dates=rows.map(row=>row.map((value,index)=>[10,11].includes(index)&&/^\d{4}-\d{2}-\d{2}$/.test(value)?(Date.parse(value+'T00:00:00Z')-Date.UTC(1899,11,30))/86400000:value));
sheet.getRange('A1:M16').values=[tableHeaders,...dates];
sheet.getRange('A1:M16').format.font={name:'Arial',size:11,color:'#000000'};
sheet.getRange('A1:M16').format.wrapText=true;
sheet.getRange('A1:M16').format.verticalAlignment='top';
sheet.getRange('A1:M1').format.rowHeight=34;
sheet.getRange('A2:M16').format.rowHeight=65;
for(const [col,width]of Object.entries({A:135,B:205,C:230,D:175,E:95,F:125,G:155,H:210,I:90,J:640,K:145,L:145,M:420}))sheet.getRange(`${col}:${col}`).format.columnWidthPx=width;
sheet.getRange('F2:F16').format.numberFormat='0';
sheet.getRange('K2:L16').format.numberFormat='yyyy-mm-dd';
sheet.freezePanes.freezeRows(1);
wb.recalculate();
const preview=await wb.render({sheetName:'ЖК',range:'A1:M16',scale:1,format:'png'});
await writeFile(path.join(out,'preview.png'),new Uint8Array(await preview.arrayBuffer()));
const inspect=await wb.inspect({kind:'region',sheetId:'ЖК',range:'F5:I9',maxChars:1400,tableMaxRows:5,tableMaxCols:4});
console.log(inspect.ndjson);
const xlsx=await SpreadsheetFile.exportXlsx(wb);await xlsx.save(path.join(out,'ЖК_13-11-2026_единый_формат.xlsx'));
await copyFile(path.join(out,'ЖК_13-11-2026_единый_формат.xlsx'),path.join(root,'dist/downloads/complexes.xlsx'));
await writeFile(path.join(out,'ЖК_13-11-2026_единый_формат.csv'),toCsv([tableHeaders,...rows]));
await copyFile(path.join(out,'ЖК_13-11-2026_единый_формат.csv'),path.join(root,'dist/downloads/complexes-plain.csv'));
console.log('Exported 15 rows, one sheet, no fills, tables, charts or conditional formatting.');
