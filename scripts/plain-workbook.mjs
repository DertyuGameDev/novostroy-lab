// Plain, single-sheet data export. Uses the shared authoring runtime only.
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const {records}=JSON.parse(await readFile(path.join(root,'data/complexes.json'),'utf8'));
const out=path.join(root,'outputs/2026-11-13-plain');await mkdir(out,{recursive:true});
const wb=Workbook.create(),sheet=wb.worksheets.add('ЖК');
const headers=['Город','Название ЖК','Застройщик','Район','Класс','Цена от, ₽/м²','Срок сдачи','Ссылки на источники','Дата цены в источнике','Проверено'];
const rows=records.map(r=>[r.city,r.name,r.developer,r.district,r.class,r.priceFrom,r.delivery,(r.verification==='search-index'?'Поисковый индекс: ':'')+[...new Set([r.sourceUrl,r.deliverySourceUrl||r.sourceUrl])].join('\n'),r.sourceDate||'Не указана',r.checkedAt]);
const dates=rows.map(row=>row.map((value,index)=>index>=8&&/^\d{4}-\d{2}-\d{2}$/.test(value)?(Date.parse(value+'T00:00:00Z')-Date.UTC(1899,11,30))/86400000:value));
sheet.getRange('A1:J16').values=[headers,...dates];
sheet.getRange('A1:J16').format.font={name:'Arial',size:11,color:'#000000'};
sheet.getRange('A1:J16').format.wrapText=true;
sheet.getRange('A1:J16').format.verticalAlignment='top';
sheet.getRange('A1:J1').format.rowHeight=34;
sheet.getRange('A2:J16').format.rowHeight=55;
for(const [col,width]of Object.entries({A:135,B:205,C:230,D:175,E:95,F:125,G:205,H:590,I:145,J:190}))sheet.getRange(`${col}:${col}`).format.columnWidthPx=width;
sheet.getRange('F2:F16').format.numberFormat='0';
sheet.getRange('I2:J16').format.numberFormat='yyyy-mm-dd';
sheet.freezePanes.freezeRows(1);
wb.recalculate();
const preview=await wb.render({sheetName:'ЖК',range:'A1:J16',scale:1,format:'png'});
await writeFile(path.join(out,'preview.png'),new Uint8Array(await preview.arrayBuffer()));
const inspect=await wb.inspect({kind:'region',sheetId:'ЖК',range:'E7:J9',maxChars:1800,tableMaxRows:3,tableMaxCols:6});
console.log(inspect.ndjson);
const xlsx=await SpreadsheetFile.exportXlsx(wb);await xlsx.save(path.join(out,'ЖК_13-11-2026.xlsx'));
await copyFile(path.join(out,'ЖК_13-11-2026.xlsx'),path.join(root,'dist/downloads/complexes.xlsx'));
const csv=[headers,...rows].map(row=>row.map(value=>'"'+String(value).replaceAll('"','""')+'"').join(';')).join('\n');
await writeFile(path.join(out,'ЖК_13-11-2026.csv'),'\uFEFF'+csv+'\n');
await copyFile(path.join(out,'ЖК_13-11-2026.csv'),path.join(root,'dist/downloads/complexes-plain.csv'));
console.log('Exported 15 rows, one sheet, no fills, tables, charts or conditional formatting.');
